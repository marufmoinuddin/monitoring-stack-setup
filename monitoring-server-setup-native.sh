#!/usr/bin/env bash
# =============================================================================
# monitoring-server-setup-native.sh — server half of the Grafana + Prometheus +
# http-over-ssh monitoring stack, WITHOUT Docker.
#
# Everything runs as native systemd services on local packages. No containers,
# no Docker networks, no nginx-proxy container, no socat relay.
#
# Run this ON THE SERVER. It is idempotent: safe to re-run.
# It produces client-bundle.env, which the client script consumes.
#
# Usage:
#   sudo ./monitoring-server-setup-native.sh --dry-run        # show everything, change nothing
#   sudo ./monitoring-server-setup-native.sh                  # do it (prompts before writing)
#   sudo ./monitoring-server-setup-native.sh --yes
#   sudo ./monitoring-server-setup-native.sh --add-client-key "ssh-ed25519 AAAA... dev"
#   sudo ./monitoring-server-setup-native.sh --rollback
#
# Layout it creates (all under /etc and /var/lib, distro-standard):
#   /etc/http-over-ssh/            proxy key + known_hosts  (mode 700)
#   /etc/prometheus/prometheus.yml scrape config
#   /etc/prometheus/rules/*.yml    alert rules
#   /etc/grafana/provisioning/     datasource
#   /etc/nginx/sites-available/monitoring-grafana.conf
#   systemd units: http-over-ssh, prometheus, grafana-server, node_exporter
#
# Ports: 8080 proxy (loopback), 9090 prometheus (loopback),
#        9100 node_exporter, 3000 grafana (loopback), 2201-2203 tunnels.
# Nothing except nginx 80/443 is public.
# =============================================================================
set -euo pipefail

# ---------------------------------------------------------------- defaults ---
DOMAIN="${DOMAIN:-monitoring.example.com}"
GRAFANA_HOST="${GRAFANA_HOST:-grafana}"
TUNNEL_HOST="${TUNNEL_HOST:-127.0.0.1}"     # where reverse tunnels are bound
TUNNEL_PORTS=(2201 2202 2203)
PROXY_PORT="${PROXY_PORT:-8080}"
PROM_PORT="${PROM_PORT:-9090}"
GRAFANA_PORT="${GRAFANA_PORT:-3000}"
EXPORT_PORT="${EXPORT_PORT:-9100}"
ADMIN_PORT="${ADMIN_PORT:-8099}"
RETENTION_TIME="${RETENTION_TIME:-90d}"
RETENTION_SIZE="${RETENTION_SIZE:-20GB}"
CONF_DIR="${CONF_DIR:-/etc/http-over-ssh}"
STATE_DIR="${STATE_DIR:-/var/lib/monitoring}"
SSHD_DROPIN="56-monitor-tunnel.conf"
PROXY_VERSION="${PROXY_VERSION:-0.3.7}"
BUNDLE="${BUNDLE:-/etc/http-over-ssh/client-bundle.env}"

DRY_RUN=0
ASSUME_YES=0
ROLLBACK=0
CLIENT_KEY=""
SUDO=""
# WEB_MODE:
#   nginx  - publish Grafana through nginx on your domain (HTTPS if a cert exists)
#   none   - no web server; Grafana stays on 127.0.0.1, reach it with an SSH
#            tunnel. Nothing is exposed at all.
WEB_MODE="${WEB_MODE:-nginx}"

c_ok()   { printf '\033[0;32m  ok\033[0m   %s\n' "$*"; }
c_warn() { printf '\033[0;33m  warn\033[0m %s\n' "$*"; }
c_err()  { printf '\033[0;31m  fail\033[0m %s\n' "$*" >&2; }
c_step() { printf '\n\033[1;36m==>\033[0m \033[1m%s\033[0m\n' "$*"; }
c_note() { printf '       %s\n' "$*"; }
die()    { c_err "$*"; exit 1; }
have()   { command -v "$1" >/dev/null 2>&1; }

sh_run() {
  if [ "$DRY_RUN" -eq 1 ]; then
    printf '       [dry-run] %s\n' "$1"
  else
    bash -c "$1"
  fi
}

confirm() {
  [ "$ASSUME_YES" -eq 1 ] && return 0
  [ "$DRY_RUN" -eq 1 ] && return 0
  local r
  read -r -p "  proceed? [y/N] " r
  case "$r" in [yY]*) return 0 ;; *) die "aborted by operator" ;; esac
}

usage() {
  sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'
  exit 0
}

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run)        DRY_RUN=1 ;;
    --yes|-y)         ASSUME_YES=1 ;;
    --rollback)       ROLLBACK=1 ;;
    --domain)         DOMAIN="$2"; shift ;;
    --grafana-host)   GRAFANA_HOST="$2"; shift ;;
    --tunnel-host)    TUNNEL_HOST="$2"; shift ;;
    --add-client-key) CLIENT_KEY="$2"; shift ;;
    --web)            WEB_MODE="$2"; shift ;;
    --help|-h)        usage ;;
    *) die "unknown option: $1 (try --help)" ;;
  esac
  shift
done

[ "$(id -u)" -eq 0 ] && SUDO="" || { have sudo || die "sudo not found"; SUDO="sudo"; }

# Validate --web up front. Placing this inside the `none` branch would make it
# unreachable for every other value, so a typo silently fell through to nginx.
case "$WEB_MODE" in
  nginx|none) ;;
  *) die "--web must be 'nginx' or 'none' (got '$WEB_MODE')" ;;
esac

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

write_native_bundle() {
  c_step "Client bundle"
  VPS_IP="$(ip -4 -br addr show scope global 2>/dev/null | awk '{print $3}' | cut -d/ -f1 | head -1)"
  [ -z "$VPS_IP" ] && VPS_IP="<set-your-server-ip>"
  HOST_FPR="$(ssh-keygen -lf /etc/ssh/ssh_host_ed25519_key.pub 2>/dev/null | awk '{print $2}')"
  PROXY_PUB=""
  [ -f "$CONF_DIR/id_ed25519.pub" ] && PROXY_PUB="$(cat "$CONF_DIR/id_ed25519.pub")"
  GF_PW=""
  [ -f "$STATE_DIR/grafana-admin-password" ] && GF_PW="$(cat "$STATE_DIR/grafana-admin-password")"

  if [ "$DRY_RUN" -eq 0 ]; then
    umask 077
    cat > "$BUNDLE" <<EOF
# Generated by monitoring-server-setup-native.sh. Mode 600 — contains a password.
#   scp <server>:$BUNDLE <client>:
#   ./monitoring-client-setup.sh --bundle client-bundle.env
VPS_HOST=$VPS_IP
VPS_HOST_KEY_FINGERPRINT=$HOST_FPR
TUNNEL_PORT=${TUNNEL_PORTS[0]}
PROXY_PUBKEY=$PROXY_PUB
GRAFANA_URL=$1
GRAFANA_USER=admin
GRAFANA_PASSWORD=$GF_PW
EOF
    chmod 600 "$BUNDLE"
    c_ok "written: $BUNDLE"
  else
    c_note "[dry-run] would write $BUNDLE"
  fi
}

native_summary() {
cat <<EOF

$(printf '\033[1;32m')=========================================================
 Native server setup complete — no Docker involved.
=========================================================$(printf '\033[0m')

 Grafana: $1
   admin / password in $STATE_DIR/grafana-admin-password

 Next, on each client machine:

   scp $BUNDLE ./monitoring-client-setup.sh <client>:
   chmod +x monitoring-client-setup.sh
   ./monitoring-client-setup.sh --bundle client-bundle.env --dry-run
   ./monitoring-client-setup.sh --bundle client-bundle.env --name my-laptop

 Then back here:

   ./monitoring-server-setup-native.sh --add-client-key "ssh-ed25519 AAAA... my-laptop"

 Verify:
   systemctl status http-over-ssh prometheus grafana-server
   curl -s http://127.0.0.1:$PROM_PORT/api/v1/query?query=up

EOF
}


# =================================================== distro / package layer ==
detect_distro() {
  if   [ -r /etc/os-release ]; then . /etc/os-release; echo "${ID:-unknown}"
  else echo unknown; fi
}
DISTRO="$(detect_distro)"
case "$DISTRO" in
  debian|ubuntu) PKGS="apt-get"; PKG_N="prometheus prometheus-node-exporter" ;;
  fedora|rhel|centos|rocky|alma) PKGS="dnf"; PKG_N="prometheus node_exporter" ;;
  arch)           PKGS="pacman"; PKG_N="prometheus prometheus-node-exporter" ;;
  alpine)         PKGS="apk";  PKG_N="prometheus node_exporter" ;;
  opensuse*)      PKGS="zypper"; PKG_N="prometheus prometheus-node_exporter" ;;
  *) c_warn "unrecognised distro '$DISTRO' — assuming apt-get"; PKGS="apt-get"
     PKG_N="prometheus prometheus-node-exporter" ;;
esac

install_pkgs() {
  case "$PKGS" in
    apt-get) $SUDO apt-get update -qq
             $SUDO DEBIAN_FRONTEND=noninteractive apt-get install -y $PKG_N curl ca-certificates ;;
    dnf)     $SUDO dnf install -y $PKG_N curl ca-certificates ;;
    pacman)  $SUDO pacman -S --needed --noconfirm $PKG_N curl ca-certificates ;;
    apk)     $SUDO apk add --no-cache $PKG_N curl ca-certificates ;;
    zypper)  $SUDO zypper --non-interactive install $PKG_N curl ca-certificates ;;
  esac
}

# Grafana is not in most distro repos; add the official one.
install_grafana() {
  if have grafana-server || systemctl list-unit-files 2>/dev/null | grep -q '^grafana-server'; then
    c_ok "grafana already installed"
    return 0
  fi
  c_step "Grafana (official apt repo)"
  case "$PKGS" in
    apt-get)
      # Repo line verified live: serves Grafana 13.x for amd64/arm64.
      # Signing key fingerprint B53AE77BADB630A683046005963FA27710458545.
      sh_run "mkdir -p /etc/apt/keyrings"
      sh_run "curl -fsSL https://apt.grafana.com/gpg.key | gpg --dearmor -o /etc/apt/keyrings/grafana.gpg"
      sh_run "chmod 644 /etc/apt/keyrings/grafana.gpg"
      sh_run "printf 'deb [signed-by=/etc/apt/keyrings/grafana.gpg] https://apt.grafana.com stable main\n' > /etc/apt/sources.list.d/grafana.list"
      sh_run "apt-get update -qq"
      sh_run "DEBIAN_FRONTEND=noninteractive apt-get install -y grafana"
      ;;
    dnf)     sh_run "$SUDO dnf install -y https://dl.grafana.com/oss/rpm/grafana-enterprise-$(rpm -E %_arch).rpm" ;;
    pacman)  c_warn "install Grafana from https://grafana.com/docs/grafana/latest/setup-grafana/installation/ (not Arch official)"
             return 0 ;;
    *)       c_warn "install Grafana manually for '$DISTRO' — see https://grafana.com/docs/grafana/latest/setup-grafana/installation/" ;;
  esac
}

# ============================================================== add-client-key ==
add_client_key() {
  [ -n "$CLIENT_KEY" ] || die "--add-client-key needs a public key"
  case "$CLIENT_KEY" in
    ssh-ed25519\ *|ssh-rsa\ *|ecdsa-sha2-*\ *) ;;
    *) die "that does not look like an SSH public key" ;;
  esac

  local port="${TUNNEL_PORTS[0]}"
  local comment; comment="$(printf '%s' "$CLIENT_KEY" | awk '{print $NF}')"
  local line="restrict,port-forwarding,permitlisten=\"${TUNNEL_HOST}:${port}\" ${CLIENT_KEY}"

  c_step "Authorizing client tunnel key on ${TUNNEL_HOST}:${port}"
  sh_run "install -d -m 700 -o monitor -g monitor /home/monitor/.ssh"
  sh_run "touch /home/monitor/.ssh/authorized_keys; chown monitor:monitor /home/monitor/.ssh/authorized_keys; chmod 600 /home/monitor/.ssh/authorized_keys"

  # Merge with awk, and verify we did not drop another device's line. The read
  # must be privileged: the file is 600 and owned by monitor, so an unprivileged
  # read silently returns nothing and we would clobber the other devices.
  local tmp before=0 after
  tmp="$(mktemp)"
  if [ -s /home/monitor/.ssh/authorized_keys ]; then
    before="$(grep -cve '^[[:space:]]*$' /home/monitor/.ssh/authorized_keys || true)"
    awk -v c="$comment" 'index($0, c) == 0' /home/monitor/.ssh/authorized_keys > "$tmp"
  else
    : > "$tmp"
  fi
  printf '%s\n' "$line" >> "$tmp"
  after="$(grep -cve '^[[:space:]]*$' "$tmp" || true)"
  if [ "$before" -gt 0 ] && [ "$after" -lt "$before" ]; then
    die "merge would drop entries (had $before, produced $after) — refusing"
  fi
  echo "  --- resulting authorized_keys ($after line(s), was $before) ---"
  sed 's/^/       /' "$tmp"
  confirm
  if [ "$DRY_RUN" -eq 0 ]; then
    install -m 600 -o monitor -g monitor "$tmp" /home/monitor/.ssh/authorized_keys
    rm -f "$tmp"
    c_ok "installed: $(ssh-keygen -lf /home/monitor/.ssh/authorized_keys | tail -1)"
  else
    rm -f "$tmp"
  fi

  c_step "Waiting for the client tunnel on ${TUNNEL_HOST}:${port}"
  if [ "$DRY_RUN" -eq 1 ]; then c_note "[dry-run] would poll and pin host keys"; return 0; fi
  local ok=0
  for i in $(seq 1 30); do
    if nc -z -w 2 "$TUNNEL_HOST" "$port" 2>/dev/null; then ok=1; break; fi
    printf '       waiting... (%ds/150s) — start the client tunnel\n' "$((i*5))"
    sleep 5
  done
  [ "$ok" -eq 1 ] || { c_err "no tunnel after 150s"; return 1; }
  c_ok "tunnel is listening"

  c_step "Pinning client host key(s)"
  # ALL key types: knownhosts rejects any unlisted type for a known host.
  local scan; scan="$(mktemp)"
  ssh-keyscan -p "$port" "$TUNNEL_HOST" 2>/dev/null | grep -v '^#' > "$scan" || true
  [ -s "$scan" ] || { c_err "ssh-keyscan returned nothing"; rm -f "$scan"; return 1; }
  c_ok "$(wc -l < "$scan") host key type(s) offered:"
  ssh-keygen -lf "$scan" | sed 's/^/       /'
  echo
  echo "  Verify on the CLIENT:  ssh-keygen -lf /etc/ssh/ssh_host_ed25519_key.pub"
  echo
  confirm

  local kh="$CONF_DIR/known_hosts"
  mkdir -p "$CONF_DIR"; touch "$kh"
  { grep -v "^\[${TUNNEL_HOST}\]:${port}[[:space:]]" "$kh" 2>/dev/null || true; cat "$scan"; } > "$kh.new"
  install -m 600 "$kh.new" "$kh"; rm -f "$kh.new" "$scan"
  c_ok "known_hosts updated:"; ssh-keygen -lf "$kh" | sed 's/^/       /'

  c_step "Restarting the proxy"
  systemctl restart http-over-ssh
  sleep 2
  journalctl -u http-over-ssh -n 6 --no-pager 2>&1 | sed 's/^/       /'
  c_note "look for: SSH connection to promssh@ established"
}

# ================================================================== rollback ==
rollback() {
  c_step "Rollback"
  echo "  This removes the monitoring units, configs, user and firewall rules."
  echo "  Prometheus/Grafana data in $STATE_DIR is KEPT."
  echo "  Backups: $STATE_DIR/backups-*"
  confirm
  for u in http-over-ssh grafana-server prometheus; do
    systemctl disable --now "$u" 2>/dev/null || true
    rm -f "/etc/systemd/system/$u.service"
  done
  systemctl daemon-reload
  c_ok "units removed"

  rm -f /etc/ssh/sshd_config.d/"$SSHD_DROPIN"
  $SUDO sshd -t 2>/dev/null && systemctl reload ssh 2>/dev/null && c_ok "sshd restored"

  # Remove UFW rules by comment text, not by index (indices shift).
  if have ufw; then
    while ufw status numbered 2>/dev/null | grep -q 'monitoring tunnel\|monitoring node_exporter'; do
      local n
      n="$(ufw status numbered | grep 'monitoring tunnel\|monitoring node_exporter' | head -1 | awk -F']' '{print $1}' | tr -d '[')"
      echo y | ufw delete "$n" || break
    done
    c_ok "ufw rules removed"
  fi

  rm -f /etc/nginx/sites-enabled/"$GRAFANA_HOST.conf"
  rm -f /etc/nginx/sites-available/"$GRAFANA_HOST.conf"
  if have nginx && have systemctl; then
    nginx -t >/dev/null 2>&1 && systemctl reload nginx && c_ok "nginx vhost removed"
  fi

  userdel -r monitor 2>/dev/null && c_ok "user monitor removed" || true
  echo
  c_ok "rollback complete. Data kept in $STATE_DIR (delete it by hand to purge)."
}

[ "$ROLLBACK" -eq 1 ] && { rollback; exit 0; }
[ -n "$CLIENT_KEY" ] && { add_client_key; exit 0; }

# ================================================================ preflight ===
c_step "Preflight ($DISTRO)"
have systemctl || die "systemd is required — this script has no SysV fallback"
c_ok "systemd present"
have curl || c_warn "curl missing; needed to fetch http-over-ssh"
have ssh-keyscan || die "ssh-keyscan missing (install openssh-client)"

# Port conflicts are the most common reason a native install fails late.
c_step "Port availability"
for p in "$PROXY_PORT" "$PROM_PORT" "$GRAFANA_PORT" "$EXPORT_PORT" "${TUNNEL_PORTS[@]}"; do
  if ss -lnt 2>/dev/null | awk '{print $4}' | grep -qE "(^|:)$p\$"; then
    owner="$(ss -lntp 2>/dev/null | awk -v P=":$p\$" '$4 ~ P {print $NF}' | head -1)"
    # Grafana/prometheus may already be installed and running — that is fine.
    case "$p" in
      "$GRAFANA_PORT"|"$PROM_PORT"|"$EXPORT_PORT")
        if have systemctl && systemctl is-active --quiet "grafana-server" 2>/dev/null && [ "$p" = "$GRAFANA_PORT" ]; then
          c_ok "port $p already in use by grafana-server (expected on re-run)"
        elif have systemctl && systemctl is-active --quiet prometheus 2>/dev/null && [ "$p" = "$PROM_PORT" ]; then
          c_ok "port $p already in use by prometheus (expected on re-run)"
        elif have systemctl && systemctl is-active --quiet prometheus-node-exporter 2>/dev/null && [ "$p" = "$EXPORT_PORT" ]; then
          c_ok "port $p already in use by node_exporter (expected on re-run)"
        else
          c_warn "port $p in use: $owner"
        fi ;;
      "${TUNNEL_PORTS[0]}")
        c_ok "port $p in use — a client tunnel is up (expected)" ;;
      *)
        c_warn "port $p already in use: $owner" ;;
    esac
  else
    c_ok "port $p free"
  fi
done

# ============================================================== packages =====
c_step "Packages"
if [ "$DRY_RUN" -eq 1 ]; then
  sh_run "$PKGS install $PKG_N"
else
  install_pkgs
  c_ok "prometheus + node_exporter present"
fi
install_grafana

# =============================================================== backups ====
c_step "Backup"
BD="$STATE_DIR/backups-$(date +%F-%H%M%S)"
sh_run "mkdir -p '$BD'"
sh_run "cp -a /etc/ssh/sshd_config.d '$BD/sshd_config.d' 2>/dev/null || true"
sh_run "cp -a /etc/prometheus '$BD/prometheus' 2>/dev/null || true"
sh_run "cp -a /etc/grafana/provisioning '$BD/grafana-provisioning' 2>/dev/null || true"
sh_run "cp -a '$CONF_DIR' '$BD/http-over-ssh' 2>/dev/null || true"
sh_run "ufw status numbered > '$BD/ufw-before.txt' 2>/dev/null || true"
c_ok "backup dir: $BD"

# ========================================================== tunnel user ======
c_step "Restricted tunnel user 'monitor'"
if getent passwd monitor >/dev/null; then
  c_ok "already exists"
else
  sh_run "useradd -m -s /usr/sbin/nologin -c 'Monitoring reverse tunnels' monitor"
fi
sh_run "usermod -p '*' monitor"
sh_run "install -d -m 700 -o monitor -g monitor /home/monitor/.ssh"
sh_run "touch /home/monitor/.ssh/authorized_keys"
sh_run "chown monitor:monitor /home/monitor/.ssh/authorized_keys"
sh_run "chmod 600 /home/monitor/.ssh/authorized_keys"
c_ok "monitor: nologin, locked password, key-only"

# ================================================================ sshd =======
c_step "sshd drop-in $SSHD_DROPIN"
# Individual ports, never a range: UFW's multiport extension can be absent and
# then a range rule is accepted but never reaches the kernel.
PERMIT=""
for p in "${TUNNEL_PORTS[@]}"; do PERMIT+=" ${TUNNEL_HOST}:$p"; done
cat > "$STAGE/$SSHD_DROPIN" <<EOF
Match User monitor
    AllowTcpForwarding remote
    GatewayPorts clientspecified
    PermitListen$PERMIT
    PermitTTY no
    X11Forwarding no
    AllowAgentForwarding no
    PermitTunnel no
    ClientAliveInterval 15
    ClientAliveCountMax 3
    ForceCommand /usr/sbin/nologin
EOF
echo "  --- proposed drop-in ---"; sed 's/^/       /' "$STAGE/$SSHD_DROPIN"
confirm
sh_run "install -m 644 '$STAGE/$SSHD_DROPIN' /etc/ssh/sshd_config.d/$SSHD_DROPIN"
if [ "$DRY_RUN" -eq 0 ]; then
  sshd -t || die "sshd config INVALID — not reloading"
  c_ok "sshd -t passed"
  systemctl reload ssh
  c_ok "sshd reloaded; effective:"
  sshd -T -C user=monitor,host=x,addr=1.2.3.4 \
    | grep -Ei '^(allowtcpforwarding|gatewayports|permitlisten|forcecommand|clientaliveinterval) ' | sed 's/^/       /'
fi

# ============================================================== firewall ====
c_step "Firewall (only if ufw is present)"
if have ufw; then
  for p in "${TUNNEL_PORTS[@]}"; do
    sh_run "ufw allow from 127.0.0.1 to any port $p proto tcp comment 'monitoring tunnel $p'"
    sh_run "ufw allow from ::1 to any port $p proto tcp comment 'monitoring tunnel $p v6'"
  done
  if [ "$DRY_RUN" -eq 0 ]; then
    missing=0
    for p in "${TUNNEL_PORTS[@]}"; do
      ufw status | grep -q "port $p proto tcp.*ALLOW" || { c_err "UFW lacks port $p"; missing=1; }
    done
    [ "$missing" -eq 0 ] && c_ok "ufw verified" || c_warn "review: ufw status numbered"
  fi
else
  c_warn "ufw not installed — skipping firewall (tunnels bind to loopback by default)"
fi

# ======================================================= http-over-ssh =======
c_step "http-over-ssh $PROXY_VERSION (prebuilt release binary)"
sh_run "install -d -m 700 '$CONF_DIR'"
sh_run "install -d -m 755 '$STATE_DIR'"

if [ -x /usr/local/bin/http-over-ssh ]; then
  c_ok "already installed"
else
  ARCH="$(uname -m)"
  case "$ARCH" in
    x86_64|amd64) ASSET_ARCH="amd64" ;;
    aarch64|arm64) ASSET_ARCH="arm64" ;;
    *) c_warn "no prebuilt binary for '$ARCH'; falling back to `go install`"
       sh_run "GOBIN=/usr/local/bin go install github.com/digineo/http-over-ssh@v${PROXY_VERSION}"
       ASSET_ARCH="" ;;
  esac
  if [ -n "$ASSET_ARCH" ]; then
    URL="https://github.com/digineo/http-over-ssh/releases/download/v${PROXY_VERSION}/http-over-ssh_${PROXY_VERSION}_linux_${ASSET_ARCH}.tar.gz"
    c_note "fetching $URL"
    sh_run "curl -fsSL -o '$STAGE/hos.tgz' '$URL'"
    # Verify the published checksum when we can fetch it.
    sh_run "curl -fsSL -o '$STAGE/checksums.txt' 'https://github.com/digineo/http-over-ssh/releases/download/v${PROXY_VERSION}/checksums.txt' || true"
    if [ "$DRY_RUN" -eq 0 ] && [ -f "$STAGE/checksums.txt" ]; then
      want="$(grep "linux_${ASSET_ARCH}.tar.gz" "$STAGE/checksums.txt" | awk '{print $1}')"
      got="$(sha256sum "$STAGE/hos.tgz" | awk '{print $1}')"
      [ -n "$want" ] && [ "$want" = "$got" ] && c_ok "checksum verified" \
        || c_warn "checksum mismatch or unavailable — review before trusting this binary"
    fi
    sh_run "tar -xzf '$STAGE/hos.tgz' -C '$STAGE' http-over-ssh"
    sh_run "install -m 755 '$STAGE/http-over-ssh' /usr/local/bin/http-over-ssh"
    c_ok "installed /usr/local/bin/http-over-ssh"
  fi
fi

if [ "$DRY_RUN" -eq 0 ]; then
  c_note "version: $(/usr/local/bin/http-over-ssh -help 2>&1 | head -1)"
fi

# Proxy key
if [ -f "$CONF_DIR/id_ed25519" ]; then
  c_ok "proxy key already exists (reused)"
else
  sh_run "ssh-keygen -t ed25519 -N '' -C 'http-over-ssh@$(hostname -s)' -f '$CONF_DIR/id_ed25519' -q"
  sh_run "chmod 600 '$CONF_DIR/id_ed25519'; chmod 644 '$CONF_DIR/id_ed25519.pub'"
  c_ok "proxy key generated"
fi

# known_hosts MUST exist — the proxy log.Fatal()s without it.
# Write into the stage dir and install it, so --dry-run never touches /etc.
if [ ! -s "$CONF_DIR/known_hosts" ]; then
  cat > "$STAGE/known_hosts" <<EOF
# http-over-ssh host key pinning. The proxy refuses to start without this file
# and rejects any unlisted key type for a host it already knows, so pin every
# type the device offers:
#   ssh-keyscan -p ${TUNNEL_PORTS[0]} ${TUNNEL_HOST} 2>/dev/null | grep -v '^#' >> $CONF_DIR/known_hosts
EOF
  sh_run "install -m 600 '$STAGE/known_hosts' '$CONF_DIR/known_hosts'"
  c_ok "known_hosts placeholder created"
