# Detect an existing certificate. We must NOT invent filenames: a vhost that
# references a missing cert makes `nginx -t` fail and, worse, a reload would
# then leave the operator without a working web server.
CERT=""; CERT_KEY=""
# Rate limiting needs a limit_req_zone declared in nginx.conf's http{} block.
# A stock nginx has none, so we only emit limit_req when one actually exists —
# otherwise nginx -t fails on an unknown zone and the vhost is unusable.
HAVE_GENERAL_ZONE=0
if have nginx && nginx -T 2>/dev/null | grep -q 'limit_req_zone[^;]*zone=general'; then
  HAVE_GENERAL_ZONE=1
fi

find_cert() {
  local f d
  # Let's Encrypt / certbot
  for f in /etc/letsencrypt/live/*/fullchain.pem; do
    [ -f "$f" ] && { d="$(dirname "$f")"; CERT="$f"; CERT_KEY="$d/privkey.pem"; return 0; }
  done
  # A common single-file wildcard layout (pair with an existing vhost style)
  for f in /etc/nginx/certs/wildcard.crt /etc/nginx/ssl/wildcard.crt \
           /etc/ssl/certs/wildcard.crt /etc/nginx/certs/fullchain.pem; do
    [ -f "$f" ] && { CERT="$f"; CERT_KEY="${f%.*}.key"; [ -f "$CERT_KEY" ] && return 0; }
    [ -f "$f" ] && { d="$(dirname "$f")"; CERT="$f"; CERT_KEY="$d/$(basename "${f%.*}").key"
                     [ -f "$CERT_KEY" ] && return 0; }
  done
  return 1
}

